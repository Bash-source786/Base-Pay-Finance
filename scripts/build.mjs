import { writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
const token = process.env.POSTHOG_PROJECT_TOKEN;
const host = process.env.POSTHOG_HOST;
const supabaseUrl = process.env.SUPABASE_URL;
const supabaseKey = process.env.SUPABASE_ANON_KEY;
if (Boolean(token) !== Boolean(host)) throw new Error('Set both POSTHOG_PROJECT_TOKEN and POSTHOG_HOST, or neither.');
if (token && !/^phc_[A-Za-z0-9]+$/.test(token)) throw new Error('Use a public PostHog project token, never a personal API key.');
if (host && !['https://eu.i.posthog.com','https://us.i.posthog.com'].includes(host)) throw new Error('Set your regional PostHog ingestion host.');
if (Boolean(supabaseUrl) !== Boolean(supabaseKey)) throw new Error('Set both SUPABASE_URL and SUPABASE_ANON_KEY, or neither.');
if (supabaseUrl && !/^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/.test(supabaseUrl)) throw new Error('SUPABASE_URL must be a https://PROJECT.supabase.co URL.');
if (supabaseKey && !(/^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/.test(supabaseKey) || /^sb_publishable_[A-Za-z0-9_-]+$/.test(supabaseKey))) throw new Error('Use a public Supabase anon/publishable key, never a service role key.');
mkdirSync('dist',{recursive:true});
for (const path of ['index.html','analytics.js','auth.js','sitemap.xml']) copyFileSync(path,'dist/'+path);
writeFileSync('dist/analytics-config.js','window.BASEPAY_ANALYTICS_CONFIG = '+JSON.stringify(token ? {token,host} : null)+';\n');
writeFileSync('dist/auth-config.js','window.BASEPAY_AUTH_CONFIG = '+JSON.stringify(supabaseUrl ? {url:supabaseUrl,anonKey:supabaseKey} : null)+';\n');
